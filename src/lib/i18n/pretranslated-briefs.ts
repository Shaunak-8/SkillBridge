export function getPretranslatedText(text: string, locale: string): string | null {
  if (!text || locale === 'en') return null;
  const trimmed = text.trim();
  const direct = PRETRANSLATED_BRIEFS[trimmed]?.[locale];
  if (direct) return direct;
  const lower = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(PRETRANSLATED_BRIEFS)) {
    if (k.toLowerCase() === lower && v[locale]) return v[locale];
  }
  return null;
}
